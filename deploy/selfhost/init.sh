#!/usr/bin/env bash
# Writes deploy/selfhost/.env with fresh secrets for a self-hosted installation. Never overwrites an existing file.
# Usage: deploy/selfhost/init.sh [public-url]   (default http://localhost:3000)
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
ENV="$DIR/.env"
if [ -e "$ENV" ]; then
  echo "$ENV already exists – keep it (it holds the key that decrypts your stored API keys)." >&2
  exit 1
fi
URL="${1:-http://localhost:3000}"
rand() { openssl rand -base64 32 | tr -d '\n'; }
PG="$(openssl rand -hex 24)"
DOCKER_GID="$( (stat -c %g /var/run/docker.sock 2>/dev/null || stat -f %g /var/run/docker.sock 2>/dev/null) || echo 0)"
umask 077
cat >"$ENV" <<ENVFILE
# Generated by init.sh on $(date -u +%FT%TZ). Back this file up: without CREDENTIALS_MASTER_KEY_V1 the stored
# provider keys cannot be decrypted. Optional settings: see apps/web/.env.example.
SELF_HOSTED=true
POSTGRES_PASSWORD=$PG
DATABASE_URL=postgres://consyrion:$PG@postgres:5432/consyrion
BETTER_AUTH_SECRET=$(rand)
BETTER_AUTH_URL=$URL
CREDENTIALS_MASTER_KEY_V1=$(rand)
CREDENTIALS_ACTIVE_KEY_VERSION=1
DOCKER_GID=$DOCKER_GID
ENVFILE
echo "Wrote $ENV. Start with: docker compose -f deploy/selfhost/compose.yml up -d --build"
