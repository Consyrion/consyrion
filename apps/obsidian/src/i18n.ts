export type Locale = "en" | "de";

export function translator(locale: Locale) {
  const table = locale === "de" ? de : en;
  return (key: Key, vars: Record<string, string | number> = {}) => table[key].replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? `{${name}}`));
}

/** "auto" follows Obsidian's language (moment locale), German when it starts with "de". */
export function resolveLocale(setting: string, appLanguage: string | null | undefined): Locale {
  if (setting === "en" || setting === "de") return setting;
  return (appLanguage ?? "").toLowerCase().startsWith("de") ? "de" : "en";
}
